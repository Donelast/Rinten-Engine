using Microsoft.AspNetCore.Components;
using Microsoft.AspNetCore.Components.Rendering;

namespace Rinten.UI;

public partial class Panel
{
	//true when the tree should be re-rendered next frame.
	bool razorTreeDirty = true;
	string razorLastTreeChecksum = null;

	[Parameter]
	public RenderFragment ChildContent
	{
		get => field;
		set
		{
			field = value;

			//A fragment gives a plain panel a render tree. It is built on the next tick,
			//which has to be asked for: under ui_tick_lean a tree is not ticked every frame.
			razorTreeDirty = true;
			RequestTick();
			RefreshTicksEveryFrame();
		}
	}

	/// <summary>For razor panels, call when the state of the render tree has changed such that it would be a good idea to re-render the tree. You would usually not need to call this manually.</summary>
	public void StateHasChanged()
	{
		ThreadSafe.AssertIsMainThread();
		razorTreeDirty = true;
		RequestTick();
	}

	//Overridden/implemented by Razor templating, contains render tree checksum to determine when the render tree content has changed.
	protected virtual string GetRenderTreeChecksum() => ChildContent == null ? null : "1";
	internal bool HasRenderTree => GetRenderTreeChecksum() is not null;

	PanelRenderTreeBuilder renderTree;

	//Overridden/implemented by Razor templating to build a render tree.
	protected virtual void BuildRenderTree( RenderTreeBuilder tree )
	{
		ChildContent?.Invoke( tree );
	}

	int previousHash;

	//By overriding this you can return a hash of variables used by the Razor layout, which will cause a rebuild when changed. This is useful
	//when your layout uses a global variable because by adding it to a HashCode.Combine here you can easily trigger a build when it changes.
	protected virtual int BuildHash()
	{
		return 0;
	}

	/// <summary>A RenderFragment has been set on us, so our tree has potential changes now. Lets update and see.</summary>
	public void OnRenderFragmentChanged( Panel upTo )
	{
		if ( upTo == this )
			return;

		razorTreeDirty = true;
		RequestTick();
		Parent?.OnRenderFragmentChanged( upTo );
	}

	//Called when BuildHash answers differently than it did last frame. A panel with a render tree rebuilds it; one built by hand is told
	//here instead, so both kinds ask the same question in the same place rather than each inventing its own comparison inside Tick.
	protected virtual void OnBuildHashChanged()
	{
	}

	//Takes what BuildHash answers now as already drawn. A panel that has just rebuilt itself for its
	//own reasons calls this, so the next frame does not notice the change and rebuild it a second time.
	protected void MarkBuildHashDrawn()
	{
		try
		{
			previousHash = BuildHash();
		}
		catch ( System.Exception e )
		{
			Log.Warning( e, $"Error calculating hash on {GetType()} - {e.Message}" );
		}
	}

	internal void InternalBuildHash()
	{
		try
		{
			var hash = BuildHash();
			if ( previousHash == hash )
				return;

			previousHash = hash;
			razorTreeDirty = true;
			OnBuildHashChanged();
		}
		catch ( System.Exception e )
		{
			Log.Warning( e, $"Error calculating hash on {GetType()} - {e.Message}" );
		}
	}

	internal void InternalTreeBinds()
	{
		if ( renderTree == null )
			return;

		if ( renderTree.UpdateBinds() )
		{
			razorTreeDirty = true;
		}
	}

	//Allows building render tree from outside of the class.
	internal RenderTreeBuilder InternalRenderTree()
	{
		if ( !HasRenderTree )
			return null;

		razorTreeDirty = false;

		if ( TickTypes.Counting ) TickReasons.NoteRender( TickTypeName );

		renderTree ??= new PanelRenderTreeBuilder( this );
		razorLastTreeChecksum = GetRenderTreeChecksum();

		renderTree.Start();
		try
		{
			BuildRenderTree( renderTree );
		}
		catch ( System.Exception e )
		{
			Log.Warning( e, $"Error when building render tree on {GetType()} - {e.Message}" );
		}
		renderTree.Finish();

		//Whether the tree holds a bind decides whether it is polled every frame.
		var hasBinds = renderTree.HasBinds();

		if ( hasBinds != treeHasBinds )
		{
			treeHasBinds = hasBinds;
			RefreshTicksEveryFrame();
		}

		return renderTree;
	}

	//Called after the razor tree has been created/rendered.
	protected virtual void OnAfterTreeRender( bool firstTime )
	{

	}

	//Delete all children generated by the Razor render tree.
	internal void ClearRenderTree()
	{
		renderTree?.Clear();
		renderTree = null;
	}
}
